#!/usr/bin/env bash
# check-shell-portability.sh — линтер переносимости inline-кода скиллов и персоны.
#
# ЗАЧЕМ. Код внутри ```bash-блоков в SKILL.md и references/*.md агент не запускает
# скриптом — он вставляет его в оболочку оператора. На macOS это **zsh**, а писался код
# в расчёте на bash. Три бага этого класса уже стоили работы (живой прогон 2026-07-25):
#
#   1) inventory-scan, verify снимка: `for f in $KEY_FILES` дал ОДНУ итерацию со
#      слипшимися именами → валидный снимок объявлен битым;
#   2) rotate-secrets, шаг 5: `for d in $CONSUMER_DIRS` → `cd /opt/a /opt/b` падает
#      «too many arguments», НИ ОДИН потребитель не перезапущен после смены пароля БД;
#   3) _lib/ensure-local-env.sh: гейт проверял `$BASH_VERSION` в `source`-контексте →
#      на маке отказывал и советовал поставить Git for Windows.
#
# Правило оператора: «правило, нарушенное дважды, идёт в код». Нарушено трижды —
# отсюда этот линтер (ADR-0028). Он не просит писать переносимо, он не даёт закоммитить.
#
# ОБЛАСТЬ. `.claude/skills/**`, `.claude/agents/**`, `.claude/knowledge/**` — везде, откуда
# агент берёт код и вставляет его в оболочку оператора. Домен знаний включён не для
# симметрии: в одном `3x-ui-api.md` 31 bash-блок, и они идут в ту же оболочку.
#
# ГРАНИЦА. Проверяются ТОЛЬКО inline-блоки в markdown. Файлы `*.sh` не проверяются:
# у них шебанг `#!/usr/bin/env bash`, они реально исполняются bash, и запрещать им
# bash-конструкции было бы вредно.
#
# Использование:
#   bash scripts/check-shell-portability.sh                 # весь репозиторий
#   bash scripts/check-shell-portability.sh --root <путь>   # явный корень
#   bash scripts/check-shell-portability.sh <файл> [...]    # только указанные файлы
#
# Возврат: 0 — чисто; 1 — найдены непереносимые конструкции (выведены с объяснением).

set -u

ROOT=""
FILES=()
while [ $# -gt 0 ]; do
    case "$1" in
        --root) ROOT="${2:-}"; shift 2 ;;
        -h|--help) sed -n '2,32p' "$0"; exit 0 ;;
        *) FILES+=("$1"); shift ;;
    esac
done

if [ -z "$ROOT" ]; then
    ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || ROOT="$(pwd)"
fi

# ─────────────────────────────────────────────────────────────────────────────
# Правила. Каждое: regex @@ короткое имя @@ чем плохо @@ как чинить.
#
# Разделитель — «@@», а НЕ «|»: символ «|» нужен внутри самих регулярок
# (`(;|$)`, `(mapfile|readarray)`), и если делить поля по нему, регулярка обрежется
# на первой же альтернативе и правило замолчит. Именно это поймал тест при первом
# прогоне — два правила из семи не срабатывали вовсе.
# Границы слова — как `(^|[^[:alnum:]_])`, а НЕ `\b`: `\b` это расширение GNU grep,
# в POSIX ERE (встроенное сопоставление bash) его нет, и правило молча перестаёт
# срабатывать. Поймано тестом при переходе с grep на `[[ =~ ]]`: 15 правил из 15
# замолчали разом.
# ─────────────────────────────────────────────────────────────────────────────
RULES=(
# — дробление слов: корневая причина двух исторических багов —
'for[[:space:]]+[A-Za-z_][A-Za-z0-9_]*[[:space:]]+in[[:space:]]+\$\{?[A-Za-z_][A-Za-z0-9_]*\}?([[:space:]]*;|[[:space:]]*$|[[:space:]]+\$)@@перебор строки вместо массива@@zsh НЕ дробит $VAR на слова: цикл делает ОДНУ итерацию со склеенным значением@@список — массивом: arr=(a b); for x in "${arr[@]}"'
'(^|[^[:alnum:]_])(cd|systemctl|docker|rm|cp|mv|chmod|chown|kill|scp|rsync|apt|apt-get|yum|dnf)[[:space:]]+([a-zA-Z0-9-][a-zA-Z0-9._-]*[[:space:]]+){0,4}\$\{?[A-Za-z_][A-Za-z0-9_]*\}?([[:space:]]|[;&|)]|$)@@переменная без кавычек в аргументах команды@@в переменной список — zsh не разобьёт его на слова (боевой случай: cd /opt/a /opt/b даёт «too many arguments»); в переменной одно значение с пробелом — сломается и bash. Лечение в обоих случаях одно@@одно значение — в кавычки ("$VAR"); список — массивом ("${arr[@]}")@@unquoted'
'(^|[^[:alnum:]_])set[[:space:]]+--[[:space:]]+\$\{?[A-Za-z_]@@set -- $VAR@@zsh не дробит переменную: получится один позиционный параметр вместо нескольких@@массив: set -- "${arr[@]}"'
# — массивы: в zsh нумерация с 1 —
'\$\{#?[A-Za-z_][A-Za-z0-9_]*\[[[:space:]]*0[[:space:]]*\]@@индекс [0] у массива@@в zsh массивы нумеруются с 1: ${arr[0]} пуст, ${#arr[0]} = 0@@брать "${arr[1]}" или перебирать "${arr[@]}"'
'^[[:space:]]*[A-Za-z_][A-Za-z0-9_]*\[[[:space:]]*0[[:space:]]*\][[:space:]]*=@@присваивание в arr[0]@@в zsh это ошибка «assignment to invalid subscript range»@@нумеровать с 1 либо собирать массив целиком: arr=(…)'
'\$[A-Za-z_][A-Za-z0-9_]*\[[0-9]@@$arr[N] без фигурных скобок@@в bash это подстановка $arr плюс текст «[N]», в zsh — элемент массива: читается по-разному@@всегда "${arr[N]}" в фигурных скобках'
# — конструкции, которых в zsh нет вовсе —
'(^|[^[:alnum:]_])shopt[[:space:]]@@shopt@@команды shopt в zsh нет вообще@@обойтись без неё или вынести код в *.sh с шебангом bash'
'\$\{PIPESTATUS\[@@PIPESTATUS@@в zsh это $pipestatus (другое имя и нумерация с 1)@@проверять код возврата иначе, либо вынести в *.sh'
'(^|[^[:alnum:]_])(mapfile|readarray)[[:space:]]@@mapfile/readarray@@обеих команд в zsh нет@@читать циклом while read, либо вынести в *.sh'
'\$\{BASH_REMATCH\[@@BASH_REMATCH@@в zsh результат =~ лежит в $MATCH и $match, BASH_REMATCH пуст: условие пройдёт, а значение будет пустым@@разобрать через sed/awk, либо вынести в *.sh'
'\$\{[A-Za-z_][A-Za-z0-9_]*(\^\^|,,)\}@@смена регистра ${var^^} / ${var,,}@@в zsh это «bad substitution» — блок падает целиком@@tr "[:lower:]" "[:upper:]" или наоборот'
'\$\{![A-Za-z_]@@косвенная ссылка ${!var}@@в zsh это «bad substitution»@@eval или ассоциативный массив, либо вынести в *.sh'
'(^|[^[:alnum:]_])read[[:space:]]+(-[a-zA-Z]+([[:space:]]+[^[:space:]]+)?[[:space:]]+)*-[a-zA-Z]*a[a-zA-Z]*([[:space:]]|$)@@read -a@@в zsh чтение в массив это -A, не -a@@разобрать без read -a, либо вынести в *.sh'
# — проверка «какая у меня оболочка» —
'(\[|\[\[)[^]]*\$\{?(BASH_VERSION|ZSH_VERSION)@@проверка версии оболочки@@inline-блок вставляется в оболочку оператора, а файл через source исполняется в оболочке вызывающего: на маке BASH_VERSION пуст всегда@@проверять то, что реально нужно (наличие бинарника bash, POSIX-совместимость), а не имя текущей оболочки'
'\$\{BASH_SOURCE\[@@BASH_SOURCE@@inline-блок вставляется в оболочку, а не запускается файлом: BASH_SOURCE даёт имя оболочки, dirname от неё = "." и запасной путь не срабатывает@@отталкиваться от $(pwd) и честно это назвать'
)

# Правило 16 — только для строк живой подстановки `` !`команда` `` (ADR-0029).
# Стоит отдельно от RULES: там сопоставление ищет ДЕФЕКТ в строке, а здесь наоборот —
# требуется НАЛИЧИЕ страховки, и общий цикл такую полярность не выражает.
SUBST_GUARD_RE='(\|\||;)[[:space:]]*(true|:)[[:space:]]*$'

# Страховка проверяется НЕ как «строка кончается на || true», а чуть умнее. Проверщик
# 27.07.2026 показал семь форм, где текст кончается страховкой, а код возврата всё равно
# ненулевой — и живым запуском это доказал. Две самые дешёвые закрыты здесь:
#   `false # || true`      — страховка внутри комментария, декоративная;
#   `exit 3 || true`       — exit завершает оболочку, до страховки дело не доходит.
# Остальные (`set -e`, `trap … EXIT`, `set -o pipefail`) регуляркой не ловятся: чтобы их
# различать, нужен разборщик оболочки внутри линтера. Замок остаётся ГРУБЫМ, и это
# записано в ADR-0029 — он снижает вероятность ожога, а не доказывает код возврата.
guard_ok() {   # $1 = проверяемая команда или последняя строка блока
    local t="$1"
    # Хвостовой комментарий отрезаем: он и прячет страховку (`false # || true`),
    # и создаёт ложную тревогу (`echo ok || true # пояснение`).
    t="$(printf '%s' "$t" | sed -E 's/[[:space:]]+#[^#]*$//')"
    case "$t" in
        *exit\ [1-9]*|*exit\ \$*) return 1 ;;
    esac
    [[ "$t" =~ $SUBST_GUARD_RE ]]
}

# ─────────────────────────────────────────────────────────────────────────────
# Применение всех правил к одной строке. Вынесено в функцию, потому что строки
# приходят из ДВУХ мест: построчного прохода по ```bash-блокам и отдельного прохода
# по исполняемым блокам ```! (их границы построчной логикой не описываются, см. ниже).
# Аргументы: относительный путь, номер строки, сама строка.
# ─────────────────────────────────────────────────────────────────────────────
apply_rules() {
    local rel="$1" ln="$2" ln_text="$3"
    local trimmed_l unquoted_l _q rule re rest name why fix scope subject
    trimmed_l="${ln_text#"${ln_text%%[![:space:]]*}"}"

    unquoted_l="$ln_text"
    case "$ln_text" in
        *[\"\']*)
            unquoted_l="$(printf '%s' "$ln_text" | sed -E "s/'[^']*'/''/g; s/\"[^\"]*\"/\"\"/g")"
            _q="${unquoted_l//[!\"]/}"
            [ $(( ${#_q} % 2 )) -eq 0 ] || unquoted_l="$ln_text"
            ;;
    esac

    for rule in "${RULES[@]}"; do
        re="${rule%%@@*}"
        rest="${rule#*@@}"
        name="${rest%%@@*}"
        rest="${rest#*@@}"
        why="${rest%%@@*}"
        rest="${rest#*@@}"
        fix="${rest%%@@*}"
        scope="${rest#*@@}"
        [ "$scope" = "$fix" ] && scope="raw"
        if [ "$scope" = "unquoted" ]; then subject="$unquoted_l"; else subject="$ln_text"; fi
        if [[ "$subject" =~ $re ]]; then
            printf '❌ %s:%s — %s\n' "$rel" "$ln" "$name" >&2
            printf '   %s\n' "$trimmed_l" >&2
            printf '   почему: %s\n' "$why" >&2
            printf '   как чинить: %s\n\n' "$fix" >&2
            TOTAL_HITS=$((TOTAL_HITS + 1))
        fi
    done
}

# ─────────────────────────────────────────────────────────────────────────────
# Исполняемый блок ```! — вторая живая форма подстановки. Разбирается ЛИНЕЙНО,
# по строкам: предыдущая редакция резала строку всего файла в цикле и была
# квадратичной — 312 КБ занимали 24 секунды, полтора мегабайта вешали линтер
# насмерть (замер проверщика 27.07.2026). Здесь каждая строка читается один раз.
#
# Регулярка клиента /```!\s*\n?([\s\S]*?)\n?```/g НЕ привязана к началу строки и НЕ
# требует перевода строки, поэтому забор ловится в любом месте строки, а блок может
# открыться и закрыться в одной строке.
# ─────────────────────────────────────────────────────────────────────────────
exec_in=0; exec_start=0; exec_last=""; exec_hd=""

exec_scan_line() {   # $1 = кусок строки, принадлежащий телу блока
    local t="${1#"${1%%[![:space:]]*}"}"
    [ -n "$t" ] || return 0
    # Тело heredoc пропускаем, как и в ```bash-блоках: код внутри уходит в файл с
    # шебангом bash или на сервер. Построчный проход это делал, а прежний блочный —
    # нет, и один и тот же текст был законен в ```bash и незаконен в ```!.
    if [ -n "$exec_hd" ]; then
        [ "$t" = "$exec_hd" ] && exec_hd=""
        return 0
    fi
    case "$t" in '#'*) return 0 ;; esac
    case "$1" in
        *'<<<'*) : ;;
        *'<<'*)
            exec_hd="$(printf '%s' "$1" | sed -nE "s/.*<<-?[[:space:]]*['\"]?([A-Za-z_][A-Za-z0-9_.-]*)['\"]?.*/\1/p")"
            [ -n "$exec_hd" ] && { exec_last="$t"; return 0; }
            ;;
    esac
    apply_rules "$exec_rel" "$lineno" "$1"
    exec_last="$t"
}

exec_close() {
    if [ -n "$exec_last" ] && ! guard_ok "$exec_last"; then
        printf '❌ %s:%s — блок ```! без страховки кода возврата\n' "$exec_rel" "$exec_start" >&2
        printf '   последняя строка блока: %s\n' "$exec_last" >&2
        printf '   почему: ненулевой код исполняемого блока молча убивает ВЕСЬ ответ агента\n' >&2
        printf '   как чинить: закрыть последнюю строку блока: … || true\n\n' >&2
        TOTAL_HITS=$((TOTAL_HITS + 1))
    fi
    exec_in=0; exec_last=""; exec_hd=""
}

# ─────────────────────────────────────────────────────────────────────────────
# Сбор файлов: markdown скиллов и персоны.
# ─────────────────────────────────────────────────────────────────────────────
if [ "${#FILES[@]}" -eq 0 ]; then
    while IFS= read -r f; do FILES+=("$f"); done < <(
        find "$ROOT/.claude/skills" "$ROOT/.claude/agents" "$ROOT/.claude/knowledge" \
             -name '*.md' -type f 2>/dev/null | sort
    )
fi

TOTAL_HITS=0
SCANNED=0

# bash 3.2 (штатный на macOS) + `set -u`: обращение к пустому массиву — фатальная
# ошибка, и она маскируется под «найдены нарушения» (тот же код возврата 1).
if [ "${#FILES[@]}" -eq 0 ]; then
    echo "✅ переносимость inline-кода: проверять нечего (подходящих файлов не найдено)"
    exit 0
fi

for file in "${FILES[@]}"; do
    [ -f "$file" ] || continue
    case "$file" in *.md) ;; *) continue ;; esac
    SCANNED=$((SCANNED + 1))

    # Идём построчно, отслеживая границы ```-блоков. Проверяем ТОЛЬКО shell-блоки
    # (```bash / ```sh / ```shell) — в ```json, ```nginx, ```cron ловить нечего.
    in_block=0
    heredoc_end=""
    lineno=0
    exec_in=0; exec_last=""; exec_hd=""; exec_start=0
    exec_rel="${file#"$ROOT"/}"
    while IFS= read -r line || [ -n "$line" ]; do
        lineno=$((lineno + 1))
        trimmed="${line#"${line%%[![:space:]]*}"}"

        # Тело исполняемого блока — до всего остального.
        if [ "$exec_in" -eq 1 ]; then
            case "$line" in
                *'```'*) exec_scan_line "${line%%'```'*}"; exec_close ;;
                *)       exec_scan_line "$line" ;;
            esac
            continue
        fi
        # Открытие исполняемого блока — в ЛЮБОМ месте строки, возможно с закрытием там же.
        case "$line" in
            *'```!'*)
                exec_after="${line#*'```!'}"
                exec_in=1; exec_start="$lineno"; exec_last=""; exec_hd=""
                case "$exec_after" in
                    *'```'*) exec_scan_line "${exec_after%%'```'*}"; exec_close ;;
                    *)       exec_scan_line "$exec_after" ;;
                esac
                continue
                ;;
        esac

        # Заборы: и ``` и ~~~; язык — в любом регистре (```BASH обходил проверку).
        # Отдельная ветка — забор ```!  : это ВТОРАЯ форма живой подстановки, тело
        # такого блока Claude Code исполняет целиком (см. комментарий к формам ниже).
        case "$trimmed" in
            '```'*|'~~~'*)
                if [ "$in_block" -eq 1 ]; then
                    # Закрытие shell-exec блока: страховка обязана стоять на его
                    # последней содержательной строке — код блока уходит наружу целиком.
                    in_block=0; heredoc_end=""
                else
                    lang="$(printf '%s' "$trimmed" | sed -E 's/^(```|~~~)[[:space:]]*//' | tr 'A-Z' 'a-z')"
                    case "$lang" in
                        '!'*)     in_block=0 ;;   # разобран отдельным проходом выше
                        bash*|sh|shell*|zsh*) in_block=1 ;;
                        *) in_block=0 ;;
                    esac
                fi
                continue
                ;;
        esac

        # ── Живая подстановка (ADR-0029) ────────────────────────────────────────
        # Форм ДВЕ, и обе взяты не из головы, а из самого клиента Claude Code 2.1.220:
        #     ```!  …  ```                     — исполняемый блок
        #     (?<=^|\s)!`команда`              — инлайн, В ЛЮБОМ месте строки, по
        #                                        нескольку раз в одной строке
        # Первая редакция правила 16 знала только «строка целиком состоит из !`…`».
        # Проверщик 27.07.2026 воспроизвёл ДВЕНАДЦАТЬ обходов: текст перед подстановкой,
        # пункт списка, цитата, две подстановки в строке со страховкой лишь у второй,
        # хвостовой пробел, блок ```! — всё это среда исполняет, а замок молчал. Тот же
        # класс «иллюзии покрытия», про который в репозитории уже записан урок: замок,
        # писанный по следам одного ожога, покрывает ожог, а не класс.
        #
        # Лукбехайнда в POSIX ERE нет, поэтому «начало строки или пробел» выражено
        # группой (^|[[:space:]]) — форма `\!` этой группой не ловится, и правильно:
        # экранированную подстановку среда не исполняет (проверено).
        is_subst=0
        rest="$line"
        while [[ "$rest" =~ (^|[[:space:]])\!\`([^\`]+)\` ]]; do
            is_subst=1
            # Сохраняем совпадение СРАЗУ: guard_ok внутри делает своё сопоставление и
            # затирает BASH_REMATCH, после чего обрезка остатка падает на пустом массиве.
            subst_cmd="${BASH_REMATCH[2]}"
            subst_whole="${BASH_REMATCH[0]}"
            if ! guard_ok "$subst_cmd"; then
                rel="${file#"$ROOT"/}"
                printf '❌ %s:%s — подстановка без страховки кода возврата\n' "$rel" "$lineno" >&2
                printf '   !`%s`\n' "$subst_cmd" >&2
                printf '   почему: ненулевой код в !`…` молча убивает ВЕСЬ ответ агента — ни ошибки, ни предупреждения\n' >&2
                printf '   как чинить: закрыть команду В КОНЦЕ: … || true\n\n' >&2
                TOTAL_HITS=$((TOTAL_HITS + 1))
            fi
            # Отрезаем разобранную подстановку и идём дальше по той же строке:
            # в строке их может быть несколько, и незастрахованной может быть любая.
            #
            # Съедаем по ОДНОМУ апострофу за шаг, шаблоном из одного литерала.
            # Первая версия резала по `$subst_cmd` — и зацикливалась намертво: в команде
            # бывают символы шаблона (*, ?, [), подстановка не совпадала, строка не
            # укорачивалась, цикл крутился вечно. Линтер вис на первом же файле.
            # Режем ровно по найденному совпадению, а не «два ближайших апострофа»:
            # иначе строка `код` и !`false` давала ДВА одинаковых срабатывания, а
            # !`a || true`!`false` — ложную тревогу на второй, которую клиент не
            # исполняет (перед `!` стоит апостроф, а не пробел). Впереди ставим
            # непробельный часовой: без него `^` в регулярке снова совпадёт с началом
            # остатка и вернёт ту же ложную тревогу.
            rest="x${rest#*"$subst_whole"}"
        done

        [ "$in_block" -eq 1 ] || [ "$is_subst" -eq 1 ] || continue

        # Тело heredoc пропускаем целиком: оно уходит либо в файл с шебангом bash
        # (`cat > run.sh <<'SCRIPT'`), либо на сервер (`ssh host bash <<'REMOTE'`) —
        # там bash-конструкции законны, блокировать их было бы ложной тревогой.
        if [ -n "$heredoc_end" ]; then
            [ "$trimmed" = "$heredoc_end" ] && heredoc_end=""
            continue
        fi

        # ⚠️ ПОРЯДОК ВАЖЕН: комментарии отсекаются ДО поиска heredoc.
        # Иначе строка `# пример вызова: cat << EOF` включает режим пропуска, и весь
        # остаток блока становится невидим для всех правил — замок печатает «чисто»
        # при живых нарушениях. Восемь таких глушилок нашёл проверщик 25.07.2026,
        # эта — самая вероятная. Пропуск комментариев обязан стоять первым.
        case "$trimmed" in '#'*) continue ;; esac

        # Детект heredoc — именно РЕДИРЕКТА, а не любых двух «<» в строке.
        # Ошибка здесь дороже всех прочих: ложный heredoc глушит ВСЕ правила до конца
        # блока, и замок печатает «чисто» при живых нарушениях.
        #
        # Ищем в строке БЕЗ содержимого двойных кавычек — иначе `echo "a << b"`
        # включает пропуск (текст в кавычках командой не является). Одинарные кавычки
        # не трогаем: в них обычно и стоит сам ограничитель — `<<'EOF'`.
        # Дополнительно отсекаем:
        #   `<<<`      — herestring, тела у него нет;
        #   `$(( … ))` — арифметический сдвиг `1 << BITS`.
        # В ограничителе разрешаем дефис и точку: `<<'EOF-1'` иначе обрезался на дефисе
        # до `EOF`, строка `EOF-1` его не закрывала, и блок немел до конца.
        # После ограничителя обязан идти конец строки, `;`, `|`, `&` или `)`.
        # sed дорог (внешний процесс на каждую строку) — зовём его только когда
        # в строке вообще есть «<<». Полный прогон по репозиторию так втрое короче.
        hd_probe=""
        case "$line" in *'<<'*) hd_probe="$(printf '%s' "$line" | sed -E 's/"[^"]*"/""/g')" ;; esac
        case "$hd_probe" in
            *'<<<'*)   : ;;                       # herestring — не heredoc
            *'$(('*)   : ;;                       # арифметика — не heredoc
            *'<<'*)
                heredoc_end="$(printf '%s' "$hd_probe" | sed -nE \
                    "s/.*<<-?[[:space:]]*['\"]?([A-Za-z_][A-Za-z0-9_.-]*)['\"]?[[:space:]]*([;|&)]|\$)?[[:space:]]*\$/\\1/p")"
                ;;
        esac

        # Строка без содержимого кавычек: то, что внутри них, чаще всего уезжает
        # в ЧУЖУЮ оболочку (`ssh host "cd $dir && …"`, `bash -c "…"`), и правила
        # про дробление слов туда не распространяются.
        #
        # Вырезаем сначала ОДИНАРНЫЕ кавычки, потом двойные: иначе две кавычки из
        # разных одинарных выражений (`sed 's/"/x/' a; cd $DIRS && sed 's/"/y/' b`)
        # склеиваются в мнимую пару, и всё между ними — включая реальный дефект —
        # тихо исчезает из проверки.
        apply_rules "${file#"$ROOT"/}" "$lineno" "$line"
    done < "$file"
done

if [ "$TOTAL_HITS" -eq 0 ]; then
