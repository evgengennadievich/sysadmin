#!/usr/bin/env bash
# test-host-digest.sh — тест переходника, приносящего дайджест состояния в подстановку.
#
# ПОЧЕМУ ТЕСТ ИМЕННО ТАКОЙ. Скрипт живёт в живой подстановке (ADR-0029), а там любая
# неудача обязана превращаться в ТЕКСТ, а не в ненулевой код: ненулевой код молча
# убивает весь ответ агента — ни ошибки, ни предупреждения, пустой вывод. Поэтому
# главная проверка каждой секции — «выход 0» — и она важнее, чем содержание вывода.
#
# Настоящего сервера тест НЕ трогает: `digest_cmd` подменяется локальной командой.
# Проверяется МОЙ код (поиск конфига, сторож времени, маскировка, коды возврата),
# а не работоспособность чужого ssh.
#
# Запуск: bash scripts/test-host-digest.sh

set -u

ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SUT="$ROOT/.claude/skills/_lib/host-digest.sh"
PASS=0; FAIL=0
WORK="$(mktemp -d)"
trap 'rm -f "$WORK"/* 2>/dev/null; rmdir "$WORK" 2>/dev/null' EXIT

ok()  { PASS=$((PASS+1)); printf '  ✅ %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '  ❌ %s\n' "$1"; }

# Собирает карту инфры с заданной командой дайджеста. Пустая строка = поля нет.
make_config() {  # $1 = имя файла, $2 = digest_cmd
    if [ -z "$2" ]; then
        printf '{"version":"1.0","state":{"mode":"manual"}}\n' > "$WORK/$1"
    else
        python3 - "$WORK/$1" "$2" <<'PY'
import json, sys
json.dump({"version": "1.0", "state": {"mode": "rebuild", "digest_cmd": sys.argv[2]}},
          open(sys.argv[1], "w", encoding="utf-8"), ensure_ascii=False)
PY
    fi
    echo "$WORK/$1"
}

echo "── тест переходника host-digest ────────────────────────"
echo

# ═══════════════════════════════════════════════════════════════════════════
echo "[1] Выход всегда 0 — ненулевой код убил бы ответ агента целиком"
# ═══════════════════════════════════════════════════════════════════════════
for spec in \
    "карты инфры нет вовсе|$WORK/нет-такого.json" \
    "в карте нет state.digest_cmd|$(make_config no-cmd.json "")" \
    "команда дайджеста падает|$(make_config failing.json "exit 7")" \
    "команда дайджеста не существует|$(make_config missing.json "такой-команды-нет-12345")"
do
    label="${spec%%|*}"; cfg="${spec#*|}"
    out="$(bash "$SUT" --config "$cfg" --timeout 3 2>&1)"; rc=$?
    if [ "$rc" -eq 0 ]; then ok "$label → выход 0"; else bad "$label → выход $rc (должен быть 0)"; fi
    case "$out" in
        *"НЕ СОБРАНО"*) ok "$label → сказано «НЕ СОБРАНО», агент не будет гадать" ;;
        *) bad "$label → нет слова «НЕ СОБРАНО»: $out" ;;
    esac
done
echo

# ═══════════════════════════════════════════════════════════════════════════
echo "[2] Рабочий путь: дайджест доезжает и помечен временем"
# ═══════════════════════════════════════════════════════════════════════════
printf 'контейнеров: 8\nсобран: 2026-07-27 03:30 UTC\n' > "$WORK/digest.md"
cfg="$(make_config ok.json "cat '$WORK/digest.md'")"
out="$(bash "$SUT" --config "$cfg" --timeout 5 2>&1)"; rc=$?
[ "$rc" -eq 0 ] && ok "рабочий путь → выход 0" || bad "рабочий путь → выход $rc"
case "$out" in *"контейнеров: 8"*) ok "содержимое дайджеста доехало" ;; *) bad "содержимое потерялось: $out" ;; esac
case "$out" in *"снят 20"*)         ok "проставлено время съёмки" ;;   *) bad "нет штампа времени съёмки" ;; esac
case "$out" in *"не обновляется"*)  ok "предупреждение о протухании на месте" ;; *) bad "нет предупреждения о протухании" ;; esac
echo

# ═══════════════════════════════════════════════════════════════════════════
echo "[3] Сторож времени — зависшая команда не морозит загрузку скилла"
# ═══════════════════════════════════════════════════════════════════════════
# Подстановка исполняется ДО хода агента: зависший ssh заморозил бы сессию целиком.
# Утилиты timeout на macOS нет, сторож самодельный — тем важнее его проверить.
cfg="$(make_config hang.json "sleep 30")"
started=$(date +%s)
out="$(bash "$SUT" --config "$cfg" --timeout 2 2>&1)"; rc=$?
elapsed=$(( $(date +%s) - started ))
[ "$rc" -eq 0 ] && ok "зависшая команда → выход 0" || bad "зависшая команда → выход $rc"
if [ "$elapsed" -le 8 ]; then ok "прервано за ${elapsed}с при лимите 2с"; else bad "сторож не сработал: ${elapsed}с"; fi
echo

# ═══════════════════════════════════════════════════════════════════════════
echo "[4] Секреты маскируются — вывод инструмента переживает сессию"
# ═══════════════════════════════════════════════════════════════════════════
# Правило §6.1: вывод инструмента — такой же носитель, как файл. Дайджест собирается
# на сервере, и однажды в него попадёт лишнее; маскировка обязана стоять здесь.
cfg="$(make_config secret.json "printf 'API_TOKEN=abcdef1234567890\\nвсё ок\\n'")"
out="$(bash "$SUT" --config "$cfg" --timeout 5 2>&1)"
case "$out" in
    *abcdef1234567890*) bad "секрет утёк в подстановку как есть" ;;
    *"всё ок"*)         ok "секрет замаскирован, полезный текст сохранён" ;;
    *)                  bad "вывод потерян целиком: $out" ;;
esac
echo

# ═══════════════════════════════════════════════════════════════════════════
echo "[5] Длинный дайджест обрезается — контекст не бесконечен"
# ═══════════════════════════════════════════════════════════════════════════
cfg="$(make_config long.json "seq 1 500")"
out="$(bash "$SUT" --config "$cfg" --timeout 5 --lines 10 2>&1)"
n="$(printf '%s\n' "$out" | grep -c '^[0-9]*$')"
if [ "$n" -le 12 ]; then ok "обрезано до лимита (числовых строк: $n)"; else bad "обрезка не работает: $n строк"; fi
case "$out" in *"из 500"*) ok "сказано, сколько строк скрыто" ;; *) bad "не сказано про скрытые строки" ;; esac
echo

# ═══════════════════════════════════════════════════════════════════════════
echo "[6] Строка подстановки в скилле проходит линтер переносимости"
# ═══════════════════════════════════════════════════════════════════════════
# Правило 16 (ADR-0029): страховка кода возврата обязана стоять в конце строки.
LINTER="$ROOT/scripts/check-shell-portability.sh"
if bash "$LINTER" --root "$ROOT" "$ROOT/.claude/skills/health-check/SKILL.md" >/dev/null 2>&1; then
    ok "подстановка в health-check переносима и со страховкой"
else
    bad "линтер ругается на подстановку в health-check"
fi
echo

echo "────────────────────────────────────────────────────────"
printf 'PASS: %s   FAIL: %s\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ] || exit 1
